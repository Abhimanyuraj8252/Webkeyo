/// Skill library registry — EVERY stage of making a story video.
///
/// Stages: Script, Voicing, Video, Editing, Thumbnail, Subtitles, Music/SFX.
/// Each skill: what it does, cost, install/key, mobile OK?, when to use,
/// what it does NOT do, and whether it is working code in this repo or a
/// documented starter. No invented star counts or prices — where a number
/// is not verified here, the entry says "check GitHub" / "check the
/// provider's pricing page".
///
/// The Skills screen lists this registry grouped by stage. SKILLS.md is
/// the human-readable version of the same registry.
