/// Skills grouped by stage, in [skillStages] order.
Map<String, List<SkillEntry>> skillsByStage() {
  final out = {for (final stage in skillStages) stage: <SkillEntry>[]};
  for (final skill in skills) {
    out.putIfAbsent(skill.stage, () => []).add(skill);
  }
  return out;
}
